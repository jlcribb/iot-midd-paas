import { readFileSync,readdirSync } from "node:fs";
import { join } from "node:path";
import { describe,expect,it } from "vitest";
import { encodeManifest,expandExperiment,GDSS_EXPERIMENT_LIMITS_V1 } from "@/lib/gdss/experiment";
import { reservoirExperimentFixture } from "../fixtures/gdss-experiment";

const directory=join(process.cwd(),"src/lib/gdss/experiment");
const source=()=>readdirSync(directory).filter(v=>v.endsWith(".ts")).map(v=>readFileSync(join(directory,v),"utf8")).join("\n");
const migration=()=>readFileSync(join(process.cwd(),"../../infra/migrations/alembic/versions/0042_gdss_simulation_experimentation.py"),"utf8");
const baseline=()=>{const {design}=reservoirExperimentFixture();const manifest=expandExperiment(design);return{design,manifest,encoded:encodeManifest(manifest)};};
const ids=[...Array.from({length:40},(_,i)=>`GDS4-INV-${String(i+1).padStart(2,"0")}`),...Array.from({length:12},(_,i)=>`GDS4-ARCH-INV-${String(i+1).padStart(2,"0")}`)];
const evidence=(id:string)=>{
  const {design,manifest,encoded}=baseline(),text=source(),ddl=migration();
  if(id==="GDS4-INV-01")expect(ddl).toContain("gdss_experiment_execution_attempt");
  else if(id==="GDS4-INV-02")expect(ddl).toContain("materialized_scenario_id UUID NOT NULL");
  else if(id==="GDS4-INV-03")expect(manifest.scenarios.every(v=>["BASELINE","ALTERNATIVE","COUNTERFACTUAL"].includes(v.scenarioType))).toBe(true);
  else if(id==="GDS4-INV-04")expect(JSON.stringify(manifest)).not.toContain("EMPIRICAL");
  else if(id==="GDS4-INV-05")expect(JSON.stringify(manifest)).not.toMatch(/recommendation|action/i);
  else if(id==="GDS4-INV-06"||id==="GDS4-INV-30")expect(text).toContain('EXPERIMENT_PHYSICAL_AUTHORITY="NONE"');
  else if(id==="GDS4-INV-07")expect(manifest.scenarios.every(v=>v.experimentDesignHash===manifest.experimentDesignHash)).toBe(true);
  else if(id==="GDS4-INV-08")expect(ddl).toContain("gdss_simulation_attempt_id UUID NULL REFERENCES public.gdss_simulation_attempt");
  else if(id==="GDS4-INV-09")expect(manifest.scenarios.filter(v=>v.scenarioType==="BASELINE")).toHaveLength(1);
  else if(id==="GDS4-INV-10")expect(manifest.scenarios.every(v=>Object.keys(v.factorAssignments).length===1)).toBe(true);
  else if(id==="GDS4-INV-11")expect(manifest.scenarios.every(v=>v.controlledInputProofHash.length===64)).toBe(true);
  else if(id==="GDS4-INV-12"||id==="GDS4-INV-15"||id==="GDS4-INV-38"||id==="GDS4-ARCH-INV-10")expect(encodeManifest(expandExperiment(design))).toEqual(encoded);
  else if(id==="GDS4-INV-13"||id==="GDS4-INV-36")expect(Object.values(GDSS_EXPERIMENT_LIMITS_V1).filter(v=>typeof v==="number").every(v=>v>0&&Number.isFinite(v))).toBe(true);
  else if(id==="GDS4-INV-14"||id==="GDS4-INV-37")expect(text).not.toMatch(/Date\.now|performance\.now|createdAt/);
  else if(id==="GDS4-INV-16"||id==="GDS4-INV-17"||id==="GDS4-ARCH-INV-09")expect(text).toContain("INELIGIBLE_MISSING_REQUIRED_SCENARIO");
  else if(id==="GDS4-INV-18")expect(ddl).toContain("metric_version='GDSS_EXPERIMENT_METRICS_V1'");
  else if(id==="GDS4-INV-19")expect(text).toContain("expectedDimension");
  else if(id==="GDS4-INV-20")expect(text).toContain("simulationResultHash");
  else if(id==="GDS4-INV-21"||id==="GDS4-ARCH-INV-11")expect(JSON.stringify(manifest)).not.toContain("$binary64");
  else if(id==="GDS4-INV-22"||id==="GDS4-ARCH-INV-06")expect((ddl.match(/append_only/g)??[]).length).toBeGreaterThanOrEqual(8);
  else if(["GDS4-INV-23","GDS4-INV-24","GDS4-INV-25"].includes(id))expect(design.baseManifest).toMatchObject({modelVersionId:expect.any(String),bindingVersionId:expect.any(String),solverVersion:expect.any(String)});
  else if(id==="GDS4-INV-26")expect(text).not.toMatch(/observation|fitting|calibrat/i);
  else if(id==="GDS4-INV-27")expect(text).not.toMatch(/optimizer|objective|optimal/i);
  else if(id==="GDS4-INV-28")expect(text).not.toMatch(/from ["'][^"']*(digital-twin|dte)/i);
  else if(id==="GDS4-INV-29"||id==="GDS4-INV-33")expect(text).not.toMatch(/control-engine/i);
  else if(id==="GDS4-INV-31")expect(text).not.toMatch(/telemetry/i);
  else if(id==="GDS4-INV-32")expect(text).not.toMatch(/mqtt/i);
  else if(id==="GDS4-INV-34")expect(text).not.toMatch(/from ["'][^"']*dte/i);
  else if(id==="GDS4-INV-35")expect(text).not.toMatch(/actuation|device command/i);
  else if(id==="GDS4-INV-39")expect(manifest.comparisons.every(v=>Number.isInteger(v.referenceScenarioOrdinal)&&Number.isInteger(v.targetScenarioOrdinal))).toBe(true);
  else if(id==="GDS4-INV-40")expect(text).not.toMatch(/SCIENTIFICALLY_VALID|scientificAuthority/i);
  else if(id==="GDS4-ARCH-INV-01")expect(text).toContain("terminalClassification");
  else if(id==="GDS4-ARCH-INV-02")expect(text).toContain("temporalCompatibility");
  else if(id==="GDS4-ARCH-INV-03")expect(text).toContain("INELIGIBLE_REFERENCE_ZERO");
  else if(id==="GDS4-ARCH-INV-04")expect(ddl).toContain("Incomplete scenario universe at RUNNING");
  else if(id==="GDS4-ARCH-INV-05")expect(text).not.toMatch(/\beval\b|new Function|dynamic import|callback|plugin/i);
  else if(id==="GDS4-ARCH-INV-07")expect(ddl).toContain("UNIQUE(experiment_attempt_id,ordinal)");
  else if(id==="GDS4-ARCH-INV-08")expect(ddl).toContain("gdss_simulation_attempt_id");
  else if(id==="GDS4-ARCH-INV-12")expect(ddl).toContain("UNIQUE(experiment_attempt_id,sequence)");
  else expect(true).toBe(true);
};

describe("GDSS-004 52-invariant gate",()=>{
  it("contains exactly 40 baseline and 12 architecture invariants",()=>{expect(ids).toHaveLength(52);expect(ids.filter(v=>v.startsWith("GDS4-INV"))).toHaveLength(40);expect(ids.filter(v=>v.startsWith("GDS4-ARCH"))).toHaveLength(12);});
  it.each(ids)("%s PASS",id=>evidence(id));
  it("migration creates exactly the approved 15 tables and no later revision",()=>{expect((migration().match(/CREATE TABLE public\.gdss_experiment_/g)??[])).toHaveLength(15);expect(migration()).not.toContain("0043");});
});
